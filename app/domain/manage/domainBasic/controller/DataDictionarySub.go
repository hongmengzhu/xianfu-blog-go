// Detail 详情
//
//	@Description:
//	@receiver c
//	@param ctx
func (c *DataDictionarySubController) Detail(ctx *gin.Context) {
	param := ctx.Param("id")
	if "" == param {
		ctx.JSON(200, rg.Error[string]("id不能为空"))
		return
	}
	ctx.JSON(200, c.sv.Detail(ctx, param))
}

