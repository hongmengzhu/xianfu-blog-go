func init() {
	gs.Provide(new(BookmarkController)).Name("ManageBookmarkController").Export(gs.As[routerPg.RouteRegistrar]())
}

// BookmarkController 书签
// @Description:
type BookmarkController struct {
	routerPg.RouteRegistrar
	Sp *authPg.GroupManageMiddlewareSp `autowire:""`
	sv *service.BlogBookmarkService    `autowire:"?"`
}

// RegisterRoutes 注册路由
//
//	@Description:
//	@receiver c
//	@param e
func (c *BookmarkController) RegisterRoutes(e *gin.Engine) {
	group := e.Group("/xianfu/manage/blog/bookmark", authPg.GroupManageMiddleware(c.Sp))
	group.POST("/createUpdate", c.CreateUpdate)
	group.GET("/detail/:id", c.Detail)
	group.POST("/enable", c.Enable)
	group.POST("/disable", c.Disable)
	group.POST("/state", c.State)
	group.POST("/delete", c.Delete)
	group.POST("/recovery", c.Recovery)
	group.POST("/physicalDeletion", c.PhysicalDeletion)
	group.POST("/query", c.Query)
	group.POST("/selectNodePublic", c.SelectNodePublic)
	group.POST("/selectNodeAllPublic", c.SelectNodeAllPublic)
	group.POST("/existName", c.ExistName)
	group.POST("/existNo", c.ExistNo)
}

// CreateUpdate 创建
//
//	@Description:
//	@receiver c
//	@param ctx
func (c *BookmarkController) CreateUpdate(ctx *gin.Context) {
	var ct modBlogBookmark.CreateUpdateCt
	if !routerPg.BindJson(ctx, &ct) {
		return
	}
	if ct.ID.ToInt64() > 0 {
		ctx.JSON(200, c.sv.Update(ctx, ct))
	} else {
		ctx.JSON(200, c.sv.Create(ctx, ct))
	}
}

// Delete 逻辑删除
//
//	@Description:
//	@receiver c
//	@param ctx
func (c *BookmarkController) Delete(ctx *gin.Context) {
	var ct model.BaseIdsCt[string]
	if !routerPg.BindJson(ctx, &ct) {
		return
	}
	ctx.JSON(200, c.sv.LogicalDeletion(ctx, ct.Ids))
}

