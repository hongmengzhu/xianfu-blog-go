// Detail 详情
func (c *IdpMetadataCacheController) Detail(ctx *gin.Context) {
	param := ctx.Param("id")
	fmt.Println(param)
	if "" == param {
		ctx.JSON(200, rg.Error[string]("id不能为空"))
		return
	}
	ctx.JSON(200, c.sv.Detail(ctx, strPg.ToInt64(param)))
}

